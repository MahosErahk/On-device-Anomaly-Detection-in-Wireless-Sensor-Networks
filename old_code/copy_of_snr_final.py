def add_random_noise(X):
    """Add random noise with std sampled uniformly for each sample."""
    X_noisy = np.copy(X)
    for i in range(len(X)):
        std = np.random.uniform(0.01, 0.20)   # random noise level per sample
        X_noisy[i] = X[i] + np.random.normal(0, std, X[i].shape).astype(np.float32)
    return X_noisy

