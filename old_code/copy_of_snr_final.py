def add_noise_snr(clean, snr_db):
    signal_power = np.mean(clean**2)
    snr_linear = 10**(snr_db / 10)
    noise_power = signal_power / snr_linear
    noise = np.random.normal(0, np.sqrt(noise_power), clean.shape)
    return clean + noise


