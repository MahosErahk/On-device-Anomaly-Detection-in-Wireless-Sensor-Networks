def add_noise(x, std):
    return x + np.random.normal(0, std, x.shape).astype(np.float32)

def compute_snr(clean, recon):
    signal_power = np.sum(clean ** 2)
    noise_power  = np.sum((clean - recon) ** 2) + 1e-10
    return 10.0 * np.log10(signal_power / noise_power)

def get_reconstruction(model, noisy_input):
    out = model.predict(noisy_input[np.newaxis, ...], verbose=0)
    if isinstance(out, (list, tuple)):
        recon = np.array(out[3])    # reconstruction is index 3
    else:
        recon = np.array(out)
    return recon.squeeze()


