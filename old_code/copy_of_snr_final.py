def channel_impulse_response(t, V_D, R_beta, A_eff_zeta, d_LOS, c,
                             N, K, R_betak, A_eff_zetak, d_kR, d_j1j,
                             alpha=0.02, nlos_scale=100):
    h_total = np.zeros_like(t)
    h_LOS   = np.zeros_like(t)
    h_NLOS  = np.zeros_like(t)

    tau_LOS = d_LOS / c
    idx_LOS = np.argmin(np.abs(t - tau_LOS))
    h_LOS[idx_LOS] = (V_D * R_beta * A_eff_zeta) / (d_LOS ** 2) * np.exp(-alpha * d_LOS)

    for i in range(N):
        total_len  = np.sum(d_j1j[i, :K]) + d_kR[i, K - 1]
        tau_path   = total_len / c
        idx        = np.argmin(np.abs(t - tau_path))
        scatter_loss = np.prod(R_betak[i, :K] * A_eff_zetak[i, :K])
        amp        = scatter_loss / (total_len ** 2) * np.exp(-alpha * total_len)
        h_NLOS[idx] += nlos_scale * amp

    return h_LOS + h_NLOS, h_LOS, h_NLOS


def calculate_channel_metrics(h_total, h_LOS, h_NLOS, t):
    P_LOS      = np.sum(h_LOS ** 2)
    P_NLOS     = np.sum(h_NLOS ** 2)
    eps        = 1e-30
    LGR_raw    = 10.0 * np.log10(max(P_LOS, eps) / max(P_NLOS, eps))
    LGR_compressed = 40.0 * np.tanh(LGR_raw / 40.0)
    pdp        = h_total ** 2
    t_ns       = t * 1e9
    if np.sum(pdp) > 0:
        tau_avg = np.sum(pdp * t_ns) / np.sum(pdp)
        tau_rms = np.sqrt(np.sum(pdp * (t_ns - tau_avg) ** 2) / np.sum(pdp))
    else:
        tau_rms = 0.0
    los_dominant = 1 if LGR_raw > 10.0 else 0
    return LGR_compressed, tau_rms, los_dominant

