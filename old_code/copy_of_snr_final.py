def sense_block(x, units=64, dropout=0.2, extra_layers=0):
    x = layers.Dense(units, activation="relu")(x)
    x = layers.LayerNormalization()(x)
    x = layers.Dropout(dropout)(x)
    for _ in range(extra_layers):
        x = layers.Dense(units, activation="relu")(x)
        x = layers.LayerNormalization()(x)
        x = layers.Dropout(dropout)(x)
    return x


def build_baseline_model(seq_len=1000, features=1):
    inputs = layers.Input(shape=(seq_len, features))

    # Encoder
    x = layers.Conv1D(32, 3, activation='relu', padding='same')(inputs)
    x = layers.MaxPooling1D(2)(x)
    x = layers.Conv1D(16, 3, activation='relu', padding='same')(x)
    x = layers.MaxPooling1D(2)(x)
    bottleneck = layers.Conv1D(8, 3, activation='relu', padding='same')(x)

    # Reconstruction head
    rx = layers.UpSampling1D(2)(bottleneck)
    rx = layers.Conv1D(16, 3, activation='relu', padding='same')(rx)
    rx = layers.UpSampling1D(2)(rx)
    rx = layers.Conv1D(32, 3, activation='relu', padding='same')(rx)
    reconstruction = layers.Conv1D(features, 1, activation='linear',
                                   name='reconstruction')(rx)

    # Sense block for metric heads
    flat   = layers.Flatten()(bottleneck)
    sense  = sense_block(flat, units=128, dropout=0.2)

    delay_out = layers.Dense(64, activation='relu')(sense)
    delay_out = layers.Dense(1, name='delay_output')(delay_out)

    lgr_out   = layers.Dense(64, activation='relu')(sense)
    lgr_out   = layers.Dense(1, activation='tanh', name='lgr_output')(lgr_out)

    cls_out   = layers.Dense(64, activation='relu')(sense)
    cls_out   = layers.Dense(1, activation='sigmoid', name='class_output')(cls_out)

    return Model(inputs, [delay_out, lgr_out, cls_out, reconstruction])


@tf.keras.utils.register_keras_serializable()
class TransformerBlock(layers.Layer):
    def __init__(self, d_model, num_heads, d_ff, dropout_rate=0.1, **kwargs):
        super().__init__(**kwargs)
        self.d_model      = d_model
        self.num_heads    = num_heads
        self.d_ff         = d_ff
        self.dropout_rate = dropout_rate
        self.attn         = layers.MultiHeadAttention(num_heads=num_heads, key_dim=d_model)
        self.ffn          = tf.keras.Sequential([
            layers.Dense(d_ff, activation="relu"),
            layers.Dense(d_model),
        ])
        self.norm1    = layers.LayerNormalization(epsilon=1e-6)
        self.norm2    = layers.LayerNormalization(epsilon=1e-6)
        self.dropout1 = layers.Dropout(dropout_rate)
        self.dropout2 = layers.Dropout(dropout_rate)

    def call(self, x, training=False, mask=None):
        attn_out = self.attn(x, x, x, attention_mask=mask)
        attn_out = self.dropout1(attn_out, training=training)
        out1     = self.norm1(x + attn_out)
        ffn_out  = self.ffn(out1)
        ffn_out  = self.dropout2(ffn_out, training=training)
        return self.norm2(out1 + ffn_out)

    def get_config(self):
        config = super().get_config()
        config.update({
            "d_model"     : self.d_model,
            "num_heads"   : self.num_heads,
            "d_ff"        : self.d_ff,
            "dropout_rate": self.dropout_rate,
        })
        return config


def build_transformer_model(seq_len=1000, features=1, latent_dim=64,
                            num_heads=4, d_ff=None):
    if d_ff is None:
        d_ff = 2 * latent_dim

    inputs = layers.Input(shape=(seq_len, features))

    x = layers.Conv1D(16, 5, activation="relu", padding="same")(inputs)
    x = layers.MaxPooling1D(2)(x)
    x = layers.Conv1D(32, 5, activation="relu", padding="same")(x)
    x = layers.MaxPooling1D(2)(x)
    x = layers.Dense(latent_dim)(x)
    x = TransformerBlock(d_model=latent_dim, num_heads=num_heads, d_ff=d_ff)(x)

    gap    = layers.GlobalAveragePooling1D()(x)
    gmp    = layers.GlobalMaxPooling1D()(x)
    latent = layers.Concatenate(name="latent_concat")([gap, gmp])

    ds_sense  = sense_block(latent, units=256, dropout=0.3, extra_layers=2)
    delay_out = layers.Dense(1, name="delay_output")(ds_sense)

    lgr_sense = sense_block(latent, units=128, dropout=0.3, extra_layers=2)
    lgr_out   = layers.Dense(1, name="lgr_output")(lgr_sense)

    cls_sense = sense_block(latent, units=64, dropout=0.2, extra_layers=1)
    class_out = layers.Dense(1, activation="sigmoid", name="class_output")(cls_sense)

    recon_x   = layers.TimeDistributed(layers.Dense(latent_dim, activation="relu"))(x)
    recon_x   = layers.UpSampling1D(2)(recon_x)
    recon_x   = layers.Conv1D(32, 5, activation="relu", padding="same")(recon_x)
    recon_x   = layers.UpSampling1D(2)(recon_x)
    recon_x   = layers.Conv1D(16, 5, activation="relu", padding="same")(recon_x)
    recon_out = layers.Conv1D(features, 1, activation="linear",
                              padding="same", name="reconstruction")(recon_x)

    return Model(inputs, [delay_out, lgr_out, class_out, recon_out])

