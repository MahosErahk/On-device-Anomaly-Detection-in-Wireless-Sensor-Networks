import numpy as np
import matplotlib.pyplot as plt

def plot_best_reconstruction(X_val, pred_reconstruction, save_path):
    """
    Plots only the BEST reconstruction sample (lowest NMSE)
    """

    nmse_list = []

    # ---- Compute NMSE ----
    for i in range(X_val.shape[0]):
        true_cir = X_val[i, :, 0]
        recon_cir = pred_reconstruction[i, :, 0]

        denom = np.sum(true_cir ** 2)
        nmse = np.sum((true_cir - recon_cir) ** 2) / denom if denom != 0 else np.inf
        nmse_list.append(nmse)

    nmse_arr = np.array(nmse_list)
    valid_idx = np.where(np.isfinite(nmse_arr))[0]

    # ---- Select BEST ----
    if len(valid_idx) == 0:
        best_idx = 0
    else:
        best_idx = valid_idx[np.argmin(nmse_arr[valid_idx])]

    true_cir = X_val[best_idx, :, 0]
    recon_cir = pred_reconstruction[best_idx, :, 0]

    # ---- Plot ----
    plt.figure(figsize=(12, 4))

    x = np.arange(len(true_cir))

    # Improved line clarity
    plt.plot(x, true_cir, label="True CIR", linewidth=2)
    plt.plot(x, recon_cir, linestyle="--", linewidth=2, alpha=0.9, label="Reconstruction")

    # ---- Remove x-axis padding ----
    plt.xlim(0, len(true_cir) - 1)

    # ---- Styling ----
    xticks = np.linspace(0, len(true_cir)-1, 6, dtype=int)
    yticks = np.linspace(min(true_cir.min(), recon_cir.min()),
                         max(true_cir.max(), recon_cir.max()), 5)

    plt.xticks(xticks, fontsize=14, fontweight='bold')
    plt.yticks(yticks, fontsize=14, fontweight='bold')

    plt.xlabel("Time Index / Tap", fontsize=14, fontweight='bold')
    plt.ylabel("Amplitude", fontsize=14, fontweight='bold')

    # Improved grid
    plt.grid(True, linestyle='--', linewidth=0.5, alpha=0.7)

    # Improved legend
    plt.legend(
        fontsize=12,
        loc="upper right",
        frameon=True,
        facecolor="white",
        edgecolor="black"
    )

    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close()

    print(f"✔ Saved BEST reconstruction plot → {save_path}")

