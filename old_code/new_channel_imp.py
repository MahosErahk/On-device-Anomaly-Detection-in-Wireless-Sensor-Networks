# ----- Transformer Block -----
class TransformerBlock(layers.Layer):
    def __init__(self, d_model, num_heads, d_ff, dropout_rate=0.1, **kwargs):
        super().__init__(**kwargs)
        self.d_model = d_model
        self.num_heads = num_heads
        self.d_ff = d_ff
        self.dropout_rate = dropout_rate

        self.attn = layers.MultiHeadAttention(num_heads=num_heads, key_dim=d_model)
        self.ffn = tf.keras.Sequential([
            layers.Dense(d_ff, activation="relu"),
            layers.Dense(d_model),
        ])
        self.norm1 = layers.LayerNormalization(epsilon=1e-6)
        self.norm2 = layers.LayerNormalization(epsilon=1e-6)
        self.dropout1 = layers.Dropout(dropout_rate)
        self.dropout2 = layers.Dropout(dropout_rate)

    def call(self, x, training=False, mask=None):
        attn_out = self.attn(x, x, x, attention_mask=mask)
        attn_out = self.dropout1(attn_out, training=training)
        out1 = self.norm1(x + attn_out)
        ffn_out = self.ffn(out1)
        ffn_out = self.dropout2(ffn_out, training=training)
        return self.norm2(out1 + ffn_out)

    def get_config(self):
        config = super().get_config()
        config.update({
            "d_model": self.d_model,
            "num_heads": self.num_heads,
            "d_ff": self.d_ff,
            "dropout_rate": self.dropout_rate,
        })
        return config

# ----- Shared Sense Block -----
def sense_block(x, units=64, dropout=0.2, extra_layers=0):
    x = layers.Dense(units, activation="relu")(x)
    x = layers.LayerNormalization()(x)
    x = layers.Dropout(dropout)(x)
    for _ in range(extra_layers):
        x = layers.Dense(units, activation="relu")(x)
        x = layers.LayerNormalization()(x)
        x = layers.Dropout(dropout)(x)
    return x

# ----- Transformer Autoencoder with Reconstruction Head -----
def build_light_cir_autoencoder_with_recon(
    seq_len=1000,
    features=1,
    latent_dim=64,
    num_heads=4,
    d_ff=None,
):
    if d_ff is None:
        d_ff = 2 * latent_dim

    inputs = layers.Input(shape=(seq_len, features))

    # Encoder
    x = layers.Conv1D(16, 5, activation="relu", padding="same")(inputs)
    x = layers.MaxPooling1D(2)(x)                        # (batch, 500, 16)
    x = layers.Conv1D(32, 5, activation="relu", padding="same")(x)
    x = layers.MaxPooling1D(2)(x)                        # (batch, 250, 32)

    x = layers.Dense(latent_dim)(x)                      # (batch, 250, latent_dim)

    x = TransformerBlock(d_model=latent_dim,
                         num_heads=num_heads,
                         d_ff=d_ff)(x)

    # GAP + GMP then concat
    gap = layers.GlobalAveragePooling1D()(x)
    gmp = layers.GlobalMaxPooling1D()(x)
    latent = layers.Concatenate(name="latent_concat")([gap, gmp])

    # Delay Spread head
    ds_sense = sense_block(latent, units=256, dropout=0.3, extra_layers=2)
    delay_spread = layers.Dense(1, name="delay_output")(ds_sense)

    # LGR head
    lgr_sense = sense_block(latent, units=128, dropout=0.3, extra_layers=2)
    lgr_out = layers.Dense(1, name="lgr_output")(lgr_sense)

    # Classification head
    cls_sense = sense_block(latent, units=64, dropout=0.2, extra_layers=1)
    class_output = layers.Dense(1, activation="sigmoid", name="class_output")(cls_sense)

    # Reconstruction head
    recon_x = layers.TimeDistributed(
        layers.Dense(latent_dim, activation="relu")
    )(x)  # (batch, 250, latent_dim)

    recon_x = layers.UpSampling1D(2)(recon_x)            # -> 500
    recon_x = layers.Conv1D(32, 5, activation="relu", padding="same")(recon_x)

    recon_x = layers.UpSampling1D(2)(recon_x)            # -> 1000
    recon_x = layers.Conv1D(16, 5, activation="relu", padding="same")(recon_x)

    reconstruction = layers.Conv1D(
        features, 1, activation="linear", padding="same",
        name="reconstruction"
    )(recon_x)

    model = Model(
        inputs,
        [delay_spread, lgr_out, class_output, reconstruction]
    )
    return model

