    plt.scatter(true_lgr, pred_lgr, alpha=0.6)
    lims = [min(true_lgr.min(), pred_lgr.min()),
            max(true_lgr.max(), pred_lgr.max())]
    plt.plot(lims, lims, "r--")
    ticks = np.linspace(lims[0], lims[1], 6)
    plt.xticks(ticks, fontsize=14, fontweight='bold')
    plt.yticks(ticks, fontsize=12, fontweight='bold')
