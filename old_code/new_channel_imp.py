    plt.ylabel("Predicted LGR (dB)", fontsize=14, fontweight='bold')
    plt.grid(True)
    plt.savefig(os.path.join(model_dir, "lgr.png"), dpi=300, bbox_inches="tight")
    plt.close()

    lgr_mse = np.mean((true_lgr - pred_lgr) ** 2)

    # -------------------------------
    # 4) CIR Reconstruction (per-sample metrics)
    # -------------------------------
    mse_list, nmse_list, r2_list = [], [], []
    for i in range(X_val.shape[0]):
        true_cir = X_val[i, :, 0]
        recon_cir = pred_reconstruction[i, :, 0]

        mse = np.mean((true_cir - recon_cir) ** 2)

        denom = np.sum(true_cir ** 2)
        if denom == 0:
            nmse = np.inf
        else:
            nmse = np.sum((true_cir - recon_cir) ** 2) / denom

        try:
            r2 = r2_score(true_cir, recon_cir)
        except Exception:
            r2 = np.nan

        mse_list.append(mse)
        nmse_list.append(nmse)
        r2_list.append(r2)

    # Choose three representative samples: best, median, worst NMSE
    nmse_arr = np.array(nmse_list)
    valid_idx = np.where(np.isfinite(nmse_arr))[0]
    if valid_idx.size == 0:
        # fallback: just pick first three indices if NMSE undefined
        sample_indices = list(range(min(3, X_val.shape[0])))
    else:
        sorted_idx = valid_idx[np.argsort(nmse_arr[valid_idx])]
        best_idx = sorted_idx[0]
        worst_idx = sorted_idx[-1]
        median_pos = len(sorted_idx) // 2
        median_idx = sorted_idx[median_pos]
        sample_indices = [best_idx, median_idx, worst_idx]
        sample_indices = list(dict.fromkeys(sample_indices))  # unique, keep order
