import os
import matplotlib.pyplot as plt
from sklearn.metrics import confusion_matrix, ConfusionMatrixDisplay

def evaluate_confusion_only(model, model_name, dataset_name,
                           X_val, Ycls_val,
                           save_dir="./eval_results"):

    model_dir = os.path.join(save_dir, model_name, dataset_name)
    os.makedirs(model_dir, exist_ok=True)

    # Predict
    preds = model.predict(X_val)
    pred_map = {name: p for name, p in zip(model.output_names, preds)}
    pred_class = pred_map["class_output"].flatten()

    true_classes = Ycls_val.flatten().astype(int)
    pred_labels = (pred_class >= 0.5).astype(int)

    # Confusion matrix
    cm = confusion_matrix(true_classes, pred_labels)
    disp = ConfusionMatrixDisplay(cm, display_labels=["LOS", "NLOS"])

    disp.plot(cmap="Blues", values_format='d')

    # Styling (IEEE-ready)
    plt.xlabel("Predicted label", fontsize=14, fontweight='bold')
    plt.ylabel("True label", fontsize=14, fontweight='bold')
    plt.xticks(fontsize=14, fontweight='bold')
    plt.yticks(fontsize=14, fontweight='bold')

    for text in disp.text_.ravel():
        text.set_fontsize(14)
        text.set_fontweight('bold')



    plt.savefig(os.path.join(model_dir, "confusion_matrix.png"),
                dpi=300, bbox_inches="tight")
    plt.close()

    print(f"✔ Saved CM: {model_name} | {dataset_name}")

