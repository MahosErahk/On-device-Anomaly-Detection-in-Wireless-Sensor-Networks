# -------------------------------------------------------------------
# More physical channel model: Gaussian pulses per path
# -------------------------------------------------------------------
def channel_impulse_response(
    t,
    V_D, R_beta, A_eff_zeta, d_LOS, c,
    N,                         # number of NLOS rays
    R_betak, A_eff_zetak,      # shape (N, K_max)
    d_kR, d_j1j,               # shape (N, K_max)
    alpha=0.02,
    sigma_t_ns=2.0             # effective temporal width (ns)
):
    """
    Computes LOS and NLOS parts of the channel impulse response h(t)
    with more physically motivated pulse shapes.

    - LOS and NLOS rays are Gaussian pulses in time.
    - Each NLOS ray has its own multi-scatter path (encoded in arrays).
    """

    h_total = np.zeros_like(t, dtype=float)
    h_LOS   = np.zeros_like(t, dtype=float)
    h_NLOS  = np.zeros_like(t, dtype=float)

    # Temporal width (standard deviation) in seconds
    sigma_t = sigma_t_ns * 1e-9

    def add_gaussian_pulse(h, tau, amp):
        """Add a normalized Gaussian pulse centered at tau with amplitude amp."""
        if sigma_t <= 0:
            # Fallback: single-sample spike
            idx = np.argmin(np.abs(t - tau))
            h[idx] += amp
            return

        gauss = np.exp(-0.5 * ((t - tau) / sigma_t) ** 2)
        gauss /= (sigma_t * np.sqrt(2.0 * np.pi))  # normalized Gaussian
        h += amp * gauss

    # --------------------------------------------------------------
    # 1) LOS component: geometric loss + exp(-alpha d_LOS)
    # --------------------------------------------------------------
    tau_LOS = d_LOS / c
    amp_LOS = (V_D * R_beta * A_eff_zeta) / (d_LOS ** 2) * np.exp(-alpha * d_LOS)
    add_gaussian_pulse(h_LOS, tau_LOS, amp_LOS)

    # --------------------------------------------------------------
    # 2) NLOS components
    # --------------------------------------------------------------
    # Arrays are padded to K_max; we only use entries where d_kR > 0
    for i in range(N):
        mask = d_kR[i, :] > 0
        if not np.any(mask):
            continue

        # Total path length = sum of scatter segments + last hop
        total_len = np.sum(d_j1j[i, mask]) + d_kR[i, mask][-1]
        tau_path = total_len / c

        # Total scattering loss: product of reflectivity * effective area terms
        scatter_loss = np.prod(R_betak[i, mask] * A_eff_zetak[i, mask])

        # Geometric + atmospheric loss
        amp_i = scatter_loss / (total_len ** 2) * np.exp(-alpha * total_len)

        add_gaussian_pulse(h_NLOS, tau_path, amp_i)

    h_total = h_LOS + h_NLOS
    return h_total, h_LOS, h_NLOS


def calculate_channel_metrics(h_total, h_LOS, h_NLOS, t):
    """Calculates soft-compressed LGR (dB) and RMS delay spread (ns) robustly."""
    P_LOS = np.sum(h_LOS ** 2)
    P_NLOS = np.sum(h_NLOS ** 2)

    # Guard against zeros -> avoid +-inf in log10
    eps = 1e-30
    P_LOS_safe = max(P_LOS, eps)
    P_NLOS_safe = max(P_NLOS, eps)

    ratio = P_LOS_safe / P_NLOS_safe
    LGR_raw = 10 * np.log10(ratio)

    # Soft compression of LGR to keep dynamic range reasonable
    # This keeps values roughly in [-40, 40] dB but preserves ordering
    LGR_compressed = 40.0 * np.tanh(LGR_raw / 40.0)

    # RMS delay spread
    pdp = h_total ** 2
    t_ns = t * 1e9  # convert to ns for interpretability
    if np.sum(pdp) > 0:
        tau_avg = np.sum(pdp * t_ns) / np.sum(pdp)
        tau_rms = np.sqrt(np.sum(pdp * (t_ns - tau_avg) ** 2) / np.sum(pdp))
    else:
        tau_rms = 0.0

    return LGR_compressed, tau_rms


