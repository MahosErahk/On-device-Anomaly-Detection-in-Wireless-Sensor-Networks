def generate_dataset_imp(dataset_type="temperature", num_los=500, num_nlos=500,
                     seed=42, use_impairments=True):
    """
    dataset_type: 'temperature', 'fog', 'ozone', 'mixed'
    use_impairments: if False, returns the same base channels without extra loss.
    """
    c = 3e8
    t_full = np.linspace(0, 5e-6, 5000)
    t_limit = 1000e-9
    idx_limit = np.argmin(np.abs(t_full - t_limit))
    t = t_full[:idx_limit]
    rng = np.random.default_rng(seed)

    total_samples = num_los + num_nlos
    cir_data = np.zeros((total_samples, len(t)))
    delay_spread = np.zeros(total_samples)
    lgr_values = np.zeros(total_samples)
    labels = np.zeros(total_samples)

    # ---------------- LOS realizations ----------------
    los_count = 0
    while los_count < num_los:
        d_LOS = rng.uniform(30, 70)   # short range LOS
        N = max(1, rng.poisson(lam=1))
        K_scatter = 1

        R_betak = rng.uniform(0.3, 0.7, size=(N, K_scatter))
        A_eff_zetak = rng.uniform(0.3, 0.7, size=(N, K_scatter))
        d_kR = rng.exponential(5.0, size=(N, K_scatter)) + 1.0
        d_j1j = rng.exponential(5.0, size=(N, K_scatter))

        h_total, h_LOS, h_NLOS = channel_impulse_response(
            t, 3.0, 0.9, 0.9, d_LOS, c,
            N, K_scatter, R_betak, A_eff_zetak, d_kR, d_j1j,
            alpha=0.02, nlos_scale=10
        )

        if use_impairments:
            h_total = apply_impairments_to_cir(h_total, d_LOS, dataset_type, rng)

        # normalize for numerical stability
        max_val = max(np.max(h_total), 1e-12)
        h_total /= max_val

        LGR, tau_rms, los_dom = calculate_channel_metrics(h_total, h_LOS, h_NLOS, t)
        if los_dom == 1:
            cir_data[los_count, :] = h_total
            delay_spread[los_count] = tau_rms
            lgr_values[los_count] = LGR
            labels[los_count] = 0  # LOS
            los_count += 1

    # ---------------- NLOS realizations ----------------
    nlos_count = 0
    while nlos_count < num_nlos:
        d_LOS = 1000.0             # long range, LOS heavily attenuated
        N = max(1, rng.poisson(lam=50))
        K_scatter = max(1, rng.poisson(lam=8))

        R_betak = rng.uniform(0.3, 0.7, size=(N, K_scatter))
        A_eff_zetak = rng.uniform(0.3, 0.7, size=(N, K_scatter))
        d_kR = rng.exponential(15.0, size=(N, K_scatter)) + 1.0
        d_j1j = rng.exponential(10.0, size=(N, K_scatter))

        h_total, h_LOS, h_NLOS = channel_impulse_response(
            t, 3.0, 0.01, 0.01, d_LOS, c,
            N, K_scatter, R_betak, A_eff_zetak, d_kR, d_j1j,
             nlos_scale=100
        )

        if use_impairments:
            h_total = apply_impairments_to_cir(h_total, d_LOS, dataset_type, rng)

        max_val = max(np.max(h_total), 1e-12)
        h_total /= max_val

        LGR, tau_rms, los_dom = calculate_channel_metrics(h_total, h_LOS, h_NLOS, t)
        if los_dom == 0:
            idx = num_los + nlos_count
            cir_data[idx, :] = h_total
            delay_spread[idx] = tau_rms
            lgr_values[idx] = LGR
            labels[idx] = 1  # NLOS
            nlos_count += 1

    # ------------- Preprocessing -------------
    cir_scaler = MinMaxScaler(feature_range=(-1, 1))
    cir_data_scaled = cir_scaler.fit_transform(cir_data)
    X = cir_data_scaled.reshape(-1, cir_data_scaled.shape[1], 1)

    # LGR is already compressed via tanh; now just scale to (-1, 1)
    lgr_scaler = MinMaxScaler(feature_range=(-1, 1))
    Y_lgr_scaled = lgr_scaler.fit_transform(lgr_values.reshape(-1, 1))

    Y_reconstruction = X.copy()
    Y_delay_spread = delay_spread.reshape(-1, 1)
    Y_lgr = Y_lgr_scaled
    Y_classification = labels.astype(int)

    X_train, X_val, \
    Yrec_train, Yrec_val, \
    Yds_train, Yds_val, \
    Ylgr_train, Ylgr_val, \
    Ycls_train, Ycls_val = train_test_split(
        X, Y_reconstruction, Y_delay_spread, Y_lgr, Y_classification,
        test_size=0.2, random_state=42, stratify=Y_classification
    )

    return (X_train, X_val,
            Yrec_train, Yrec_val,
            Yds_train, Yds_val,
            Ylgr_train, Ylgr_val,
            Ycls_train, Ycls_val,
            lgr_scaler, cir_scaler)



