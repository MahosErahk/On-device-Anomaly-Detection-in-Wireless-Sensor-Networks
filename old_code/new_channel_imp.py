def epoch_to_95(loss_curve):
    loss_curve = np.array(loss_curve)
    L0 = loss_curve[0]
    Lf = loss_curve[-1]
    threshold = Lf + 0.05 * (L0 - Lf)

    for i, L in enumerate(loss_curve):
        if L <= threshold:
            return i
    return len(loss_curve) - 1

