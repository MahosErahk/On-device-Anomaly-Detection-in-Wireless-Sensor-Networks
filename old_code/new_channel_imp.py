x = Conv1D(16, 3, activation='relu', padding='same')(x)
x = MaxPooling1D(2, padding='same')(x)             # (seq_len/4, 16)
bottleneck = Conv1D(8, 3, activation='relu', padding='same', name='bottleneck')(x)  # (seq_len/4, 8)

# Flatten for shared sense block
bottleneck_flat = Flatten()(bottleneck)

# ----- Shared Sense Block -----
sense = Dense(128, activation='relu', name='shared_sense')(bottleneck_flat)
sense = Dense(64, activation='relu')(sense)  # optional second layer

