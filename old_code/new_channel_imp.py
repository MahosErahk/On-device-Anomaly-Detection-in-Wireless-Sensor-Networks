# --------------------------
# CIR functions (baseline model)
# --------------------------
def channel_impulse_response(t, V_D, R_beta, A_eff_zeta, d_LOS, c,
                             N, K, R_betak, A_eff_zetak, d_kR, d_j1j,
                             alpha=0.02, nlos_scale=100):
    """
    Simple UV channel model with one LOS spike and N NLOS spikes.
    (You already have a more physical Gaussian version for the
    'no-impairment' dataset; this one is kept for compatibility.)
    """
    h_total = np.zeros_like(t)
    h_LOS = np.zeros_like(t)
    h_NLOS = np.zeros_like(t)

    # LOS
    tau_LOS = d_LOS / c
    idx_LOS = np.argmin(np.abs(t - tau_LOS))
    h_LOS[idx_LOS] = (V_D * R_beta * A_eff_zeta) / (d_LOS ** 2) * np.exp(-alpha * d_LOS)

    # NLOS
    for i in range(N):
        total_len = np.sum(d_j1j[i, :K]) + d_kR[i, K-1]
        tau_path = total_len / c
        idx = np.argmin(np.abs(t - tau_path))
        scatter_loss = np.prod(R_betak[i, :K] * A_eff_zetak[i, :K])
        amp = scatter_loss / (total_len ** 2) * np.exp(-alpha * total_len)
        h_NLOS[idx] += nlos_scale * amp

    return h_LOS + h_NLOS, h_LOS, h_NLOS


# --------------------------
# Channel metrics (with soft LGR compression)
# --------------------------
def calculate_channel_metrics(h_total, h_LOS, h_NLOS, t):
    """
    Returns:
      LGR_compressed : soft-compressed LGR (dB) using tanh
      tau_rms        : RMS delay spread (ns)
      los_dominant   : 1 if raw LGR > 10 dB, else 0
    """
    P_LOS = np.sum(h_LOS**2)
    P_NLOS = np.sum(h_NLOS**2)

    # numeric safety
    eps = 1e-30
    P_LOS_safe = max(P_LOS, eps)
    P_NLOS_safe = max(P_NLOS, eps)

    ratio = P_LOS_safe / P_NLOS_safe
    LGR_raw = 10.0 * np.log10(ratio)

    # soft compression to keep target range sensible (~[-40, 40] dB)
    LGR_compressed = 40.0 * np.tanh(LGR_raw / 40.0)

    # PDP and RMS delay spread
    pdp = h_total**2
    t_ns = t * 1e9
    if np.sum(pdp) > 0:
        tau_avg = np.sum(pdp * t_ns) / np.sum(pdp)
        tau_rms = np.sqrt(np.sum(pdp * (t_ns - tau_avg)**2) / np.sum(pdp))
    else:
        tau_rms = 0.0

    # classification label decided on RAW LGR (not compressed)
    los_dominant = 1 if LGR_raw > 10.0 else 0

    return LGR_compressed, tau_rms, los_dominant


# --------------------------
# Improved channel impairments
# --------------------------
def apply_impairments_to_cir(h_total, d_LOS, impair_type, rng):
    """
    Applies physically-motivated attenuation based on environment.

    d_LOS      : LOS distance in meters
    impair_type: 'temperature', 'fog', 'ozone', or 'mixed'
    """
    d_km = d_LOS / 1000.0  # convert to km

    # start with no extra attenuation
    total_extinction_per_km = 0.0  # effective extinction coefficient (1/km)

    if impair_type == "temperature":
        # Temperature affects turbulence / scattering -> moderate extinction.
        # Base around room temp (20°C), stronger effect as |T-20| grows.
        temp_C = rng.uniform(-10, 45)
        k_T = 0.02  # per °C per km (heuristic, kept small)
        total_extinction_per_km += k_T * abs(temp_C - 20.0)

    elif impair_type == "fog":
        # Fog modeled via visibility-based extinction:
        # sigma_f ≈ 3.912 / V   (Kruse-like model), V in km.
        visibility_km = rng.uniform(0.2, 20.0)  # 0.2 km (dense fog) to clear
        sigma_f = 3.912 / visibility_km
        total_extinction_per_km += sigma_f

    elif impair_type == "ozone":
        # Ozone absorption coefficient at UV; use plausible range.
        # mu_O3 in [0, 0.5] 1/km (heuristic).
        mu_o3 = rng.uniform(0.0, 0.5)
        total_extinction_per_km += mu_o3

    elif impair_type == "mixed":
        # Combined environment: fog + ozone + thermal-turbulence + humidity.
        visibility_km = rng.uniform(0.2, 10.0)
        sigma_f = 3.912 / visibility_km

        mu_o3 = rng.uniform(0.1, 0.5)   # stronger ozone region

        temp_C = rng.uniform(-10, 45)
        k_T = 0.02
        ext_temp = k_T * abs(temp_C - 20.0)

        humidity_pct = rng.uniform(20, 100)
        # humidity adds mild scattering / absorption
        ext_hum = 0.01 * (humidity_pct / 100.0)  # 0–0.01 /km

        total_extinction_per_km += (sigma_f + mu_o3 + ext_temp + ext_hum)

    # Convert extinction to amplitude attenuation.
    # Intensity I ~ exp(-ext * d); amplitude ~ exp(-0.5 * ext * d).
    ext_total = total_extinction_per_km * d_km
    amp_factor = np.exp(-0.5 * ext_total)

    return h_total * amp_factor


